const languageStorageKey = "shoShopLanguage";
const storedLanguage = window.localStorage.getItem(languageStorageKey);
let activeLanguage = storedLanguage === "en" ? "en" : "id";

function translate(key, values = {}) {
    let message = translations[activeLanguage][key] || translations.id[key] || key;
    for (const [name, value] of Object.entries(values)) {
        message = message.replaceAll(`{${name}}`, String(value));
    }
    return message;
}

function applyLanguage() {
    document.documentElement.lang = activeLanguage;

    document.querySelectorAll("[data-i18n]").forEach(element => {
        element.textContent = translate(element.dataset.i18n);
    });
    document.querySelectorAll("[data-i18n-placeholder]").forEach(element => {
        element.setAttribute("placeholder", translate(element.dataset.i18nPlaceholder));
    });
    document.querySelectorAll("[data-i18n-aria]").forEach(element => {
        element.setAttribute("aria-label", translate(element.dataset.i18nAria));
    });

    const titleKey = document.body.dataset.i18nTitle;
    if (titleKey) {
        document.title = translate(titleKey);
    }
    const descriptionKey = document.body.dataset.i18nDescription;
    if (descriptionKey) {
        const description = document.querySelector('meta[name="description"]');
        if (description) {
            description.setAttribute("content", translate(descriptionKey));
        }
    }

    document.querySelectorAll("[data-language-toggle]").forEach(button => {
        button.textContent = translate("language.toggle");
        button.setAttribute("aria-label", translate("language.aria"));
    });

    document.dispatchEvent(new CustomEvent("shop:languagechange", {
        detail: { language: activeLanguage }
    }));
}

function setLanguage(language) {
    if (language !== "id" && language !== "en") {
        throw new RangeError("Unsupported language.");
    }
    activeLanguage = language;
    window.localStorage.setItem(languageStorageKey, language);
    applyLanguage();
}

document.addEventListener("click", event => {
    if (event.target.closest("[data-language-toggle]")) {
        setLanguage(activeLanguage === "id" ? "en" : "id");
    }
});

window.ShopI18n = {
    getLanguage: () => activeLanguage,
    setLanguage,
    t: translate
};

applyLanguage();
